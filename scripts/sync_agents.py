#!/usr/bin/env python3
"""Render native adapters from canonical role instructions; --check rejects drift."""
import argparse
import json
from pathlib import Path
import sys
import yaml

ROOT = Path(__file__).resolve().parents[1]


def render():
    registry = yaml.safe_load((ROOT / 'agents/REGISTRY.yml').read_text())
    common = (ROOT / 'agents/COMMON.md').read_text().strip()
    output = {}
    for role in registry['agents']:
        name = role['name']
        body = (ROOT / role['instructions']).read_text().strip()
        instructions = common + '\n\n' + body + '\n'
        data = {key: role[key] for key in ('name', 'description')}
        data['developer_instructions'] = instructions
        toml = '# Generated by scripts/sync_agents.py; edit agents/ sources instead.\n'
        toml += '\n'.join(f'{key} = {json.dumps(value, ensure_ascii=False)}' for key, value in data.items()) + '\n'
        if role['access'] == 'review':
            toml += '\n[features]\nshell_tool = false\napps = false\nplugins = false\nmemories = false\n'
        output[ROOT / f'.codex/agents/{name}.toml'] = toml
        tools = 'Read, Glob, Grep'
        if role['access'] == 'write':
            tools += ', Edit, Write'
        elif role['access'] == 'execute':
            tools += ', Bash'
        header = yaml.safe_dump({'name': name, 'description': role['description'], 'tools': tools}, sort_keys=False)
        output[ROOT / f'.claude/agents/{name}.md'] = '---\n' + header + '---\n\n' + instructions
    for skill in sorted((ROOT / '.agents/skills').glob('*/SKILL.md')):
        for source in sorted(skill.parent.rglob('*')):
            if source.is_file():
                target = ROOT / '.claude/skills' / source.relative_to(ROOT / '.agents/skills')
                output[target] = source.read_text()
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = render()
    expected = set(output)
    actual = set()
    for folder in ('.codex/agents', '.claude/agents', '.claude/skills'):
        actual.update(p for p in (ROOT / folder).rglob('*') if p.is_file())
    stale = actual - expected
    drift = [p for p, text in output.items() if not p.exists() or p.read_text() != text]
    if args.check:
        if stale or drift:
            for p in sorted(stale | set(drift)):
                print('DRIFT:', p.relative_to(ROOT), file=sys.stderr)
            return 1
        print(f'PASS: {len(output)} generated agent/skill adapter files match canonical sources')
        return 0
    for p in stale:
        p.unlink()
    for p, text in output.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f'Rendered {len(output)} native agent/skill adapter files')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
